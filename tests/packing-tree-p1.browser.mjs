import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {readFileSync} from 'node:fs';
const port=8601,url='http://127.0.0.1:'+port+'/';
const server=spawn('python3',['-m','http.server',String(port),'--bind','127.0.0.1'],{stdio:'ignore'});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,acceptDownloads:true});
const page=await context.newPage(),faults=[];
page.on('pageerror',error=>faults.push(error.message));
async function ready(){for(let i=0;i<45;i++){try{if((await fetch(url)).ok)return;}catch{}await new Promise(resolve=>setTimeout(resolve,250));}throw Error('Test server unavailable');}
try{
 await ready();await page.goto(url,{waitUntil:'domcontentloaded'});
 await page.locator('[data-view="trips"]').last().click();
 await page.locator('[data-action="new-trip"]').first().click();
 await page.locator('#f-title').fill('Packing Test');
 await page.locator('#f-startDate').fill('2026-12-05');
 await page.locator('#f-endDate').fill('2026-12-09');
 await page.locator('#modal-form button[type=submit]').click();
 await page.locator('[data-trip-tab="packing"]').click();
 await page.locator('[data-action="packing-mindmap"]').click();
 await page.locator('#packing-tree').waitFor();
 assert.equal(await page.locator('[data-pack-tree-branch]').count(),8);
 await page.locator('[data-pack-tree-add-branch]').click();
 const custom=page.locator('[data-pack-tree-branch]').last();
 await custom.locator('[data-pack-tree-group]').fill('Road food');
 await custom.locator('[data-pack-tree-item]').first().fill('Snacks');
 await custom.locator('[data-pack-tree-item]').first().press('Enter');
 await custom.locator('[data-pack-tree-item]').nth(1).fill('Water bottles');
 await page.locator('#modal-form button[type=submit]').click();
 await page.getByText('Snacks').first().waitFor();
 assert.equal(await page.locator('.packing-table tbody tr').filter({hasText:'Road food'}).count(),2);
 await page.locator('[data-action="packing-mindmap"]').click();
 const reopened=page.locator('[data-pack-tree-branch]').filter({has:page.locator('[data-pack-tree-group][value="Road food"]')});
 await reopened.waitFor();
 assert.match(await reopened.innerText(),/2 on your list/);
 await reopened.locator('[data-pack-tree-item]').first().fill('Biscuits');
 await page.locator('#modal-form button[type=submit]').click();
 await page.getByText('Biscuits').first().waitFor();
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('[data-view="trips"]').last().click();
 await page.locator('[data-trip-tab="packing"]').click();
 assert.equal(await page.locator('.packing-table tbody tr').filter({hasText:'Road food'}).count(),3);
 await page.locator('[data-view="more"]').last().click();
 const download=page.waitForEvent('download');
 await page.locator('[data-action="export-backup"]').first().click();
 const file=await download;
 const backup=JSON.parse(readFileSync(await file.path(),'utf8'));
 const rows=backup.records.filter(x=>x.type==='packing');
 assert.deepEqual(rows.map(x=>x.data.label).sort(),['Biscuits','Snacks','Water bottles']);
 assert.ok(rows.every(x=>x.data.group==='Road food'));
 assert.equal(faults.length,0,faults.join('; '));
 console.log('P1_BROWSER_PASS: mobile visual branches, Enter-to-add, custom group preservation, table and backup');
}finally{await context.close();await browser.close();server.kill();}
