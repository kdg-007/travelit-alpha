import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {readFileSync} from 'node:fs';
const port=8569,url='http://127.0.0.1:'+port+'/';
const srv=spawn('python3',['-m','http.server',String(port),'--bind','127.0.0.1'],{stdio:'ignore'});
async function waitReady(){for(let n=0;n<35;n++){try{if((await fetch(url)).ok)return;}catch{}await new Promise(r=>setTimeout(r,250));}throw Error('Test server unavailable');}
const browser=await chromium.launch({headless:true});
const ctx=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,acceptDownloads:true});
const page=await ctx.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await waitReady();
 await page.goto(url,{waitUntil:'domcontentloaded'});
 await page.locator('[data-view="trips"]').last().click();
 await page.locator('[data-action="new-trip"]').first().click();
 await page.locator('#f-title').fill('B4 Synthetic Family Trip');
 await page.locator('#f-startDate').fill('2026-12-05');
 await page.locator('#f-endDate').fill('2026-12-07');
 await page.locator('#modal-form button[type=submit]').click();
 await page.locator('[data-trip-tab="prepare"]').click();
 await page.getByText('Before you go').waitFor();
 assert.equal(await page.locator('.prepare-row').count(),4);
 await page.locator('[data-trip-tab="costs"]').click();
 await page.locator('[data-action="assign-trip-vehicle"]').first().click();
 await page.getByText('Vehicle for fuel estimates').waitFor();
 await page.locator('#modal-close').click();
 await page.locator('[data-view="more"]').last().click();
 await page.locator('[data-action="add-vehicle"]').first().click();
 await page.locator('#f-make').fill('MG');
 await page.locator('#f-model').fill('MG6');
 await page.locator('#f-nickname').fill('Family car');
 await page.locator('#f-kmPerLiter').fill('12');
 await page.locator('#f-fuelPricePhp').fill('75');
 await page.locator('#modal-form button[type=submit]').click();
 await page.locator('[data-view="trips"]').last().click();
 await page.locator('[data-trip-tab="costs"]').click();
 await page.locator('[data-action="assign-trip-vehicle"]').first().click();
 await page.locator('#f-vehicleId').selectOption({label:'Family car'});
 await page.locator('#modal-form button[type=submit]').click();
 await page.locator('[data-action="add-expense"]').first().click();
 await page.locator('#f-label').fill('Hotel test');
 await page.locator('#f-plannedPhp').fill('=3000*5');
 await page.locator('#modal-form button[type=submit]').click();
 await page.getByText('Hotel test').waitFor();
 assert.match(await page.locator('#main').innerText(),/₱15,000/);
 await page.locator('[data-trip-tab="packing"]').click();
 await page.locator('[data-action="packing-mindmap"]').click();
 const docs=page.locator('[data-pack-tree-branch]').first();
 await docs.locator('[data-pack-tree-item]').first().fill('License');
 await docs.locator('[data-pack-tree-item]').first().press('Enter');
 await docs.locator('[data-pack-tree-item]').nth(1).fill('Flashlight');
 await page.locator('[data-pack-tree-branch]').nth(2).locator('[data-pack-tree-item]').first().fill('First aid');
 await page.locator('#modal-form button[type=submit]').click();
 await page.getByText('Flashlight').waitFor();
 await page.locator('[data-view="explore"]').last().click();
 await page.locator('[data-action="show-map"]').first().click();
 await page.locator('#travelit-live-map').waitFor();
 assert.equal(await page.locator('#travelit-live-map').isVisible(),true);
 assert.equal(await page.locator('[data-action="live-map-pick"]').count(),1);
 assert.match(await page.locator('.map-advanced summary').innerText(),/Offline maps/);
 await page.locator('[data-view="more"]').last().click();
 const downloadEvent=page.waitForEvent('download');
 await page.locator('[data-action="export-backup"]').first().click();
 const downloaded=await downloadEvent;
 const backup=JSON.parse(readFileSync(await downloaded.path(),'utf8'));
 const budget=backup.records.find(r=>r.type==='expense'&&r.data?.label==='Hotel test');
 assert.ok(budget,'budget included in local backup');
 assert.equal(budget.data.plannedFormula,'=3000*5');
 assert.equal(budget.data.plannedPhp,15000);
 const vehicle=backup.records.find(r=>r.type==='vehicle'&&r.data?.name==='Family car');
 assert.equal(vehicle?.data.make,'MG');
 assert.equal(vehicle?.data.model,'MG6');
 assert.ok(backup.records.some(r=>r.type==='packing'&&r.data?.label==='Flashlight'));
 assert.equal(errors.length,0,'Unexpected errors: '+errors.join(' | '));
 console.log('B4_BROWSER_PASS: Prepare, correct vehicle editor, budget formula, mind-map packing, online map fallback');
}finally{await ctx.close();await browser.close();srv.kill();}
