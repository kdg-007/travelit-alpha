import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {readFileSync} from 'node:fs';
const port=8591,url='http://127.0.0.1:'+port+'/';
const server=spawn('python3',['-m','http.server',String(port),'--bind','127.0.0.1'],{stdio:'ignore'});
const browser=await chromium.launch({headless:true});
async function ready(){for(let i=0;i<45;i++){try{if((await fetch(url)).ok)return;}catch{}await new Promise(r=>setTimeout(r,250));}throw Error('Test server unavailable');}
const makeContext=()=>browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,acceptDownloads:true});
let context=null,second=null;
try{
 await ready();
 context=await makeContext();
 const page=await context.newPage();
 const faults=[];page.on('pageerror',e=>faults.push(e.message));
 await page.goto(url,{waitUntil:'domcontentloaded'});
 await page.locator('[data-view="trips"]').last().click();
 await page.locator('[data-action="new-trip"]').first().click();
 await page.locator('#f-title').fill('Family Sagada Test');
 await page.locator('#f-startDate').fill('2026-12-05');
 await page.locator('#f-endDate').fill('2026-12-09');
 await page.locator('#modal-form button[type=submit]').click();
 await page.locator('[data-action="add-stop"]').first().click();
 await page.locator('#f-title').fill('Morning drive');
 await page.locator('#f-time').fill('09:00');
 await page.locator('#f-durationMinutes').fill('60');
 await page.locator('#modal-form button[type=submit]').click();
 await page.locator('.timeline-bar').first().waitFor();
 assert.equal(await page.locator('.timeline-bar').count(),1);
 await page.locator('[data-action^="timeline-shift:15:"]').first().click();
 await page.getByText('09:15').first().waitFor();
 await page.locator('[data-trip-tab="info"]').click();
 await page.locator('[data-action^="add-note:trip:"]').first().click();
 await page.locator('#f-title').fill('Trip ideas');
 await page.locator('#f-content').fill('# Sagada\n- Visit the museum\n- Early breakfast\n**Keep this**');
 await page.locator('#note-save-status').getByText('Saved on this device').waitFor({timeout:15000});
 await page.locator('#modal-form button[type=submit]').click();
 await page.getByText('Trip ideas').first().waitFor();
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('[data-view="trips"]').last().click();
 await page.locator('[data-trip-tab="info"]').click();
 await page.getByText('Trip ideas').first().waitFor();
 await page.locator('[data-view="more"]').last().click();
 const downloadEvent=page.waitForEvent('download');
 await page.locator('[data-action="export-backup"]').first().click();
 const downloaded=await downloadEvent;
 const path=await downloaded.path();
 const backup=JSON.parse(readFileSync(path,'utf8'));
 assert.equal(backup.schemaVersion,6);
 const note=backup.records.find(r=>r.type==='note'&&r.data.title==='Trip ideas');
 assert.ok(note);
 assert.equal(note.data.content,'# Sagada\n- Visit the museum\n- Early breakfast\n**Keep this**');
 assert.equal(note.data.targetType,'trip');
 const stop=backup.records.find(r=>r.type==='stop'&&r.data.title==='Morning drive');
 assert.equal(stop?.data.time,'09:15');
 assert.equal(faults.length,0,faults.join('; '));
 second=await makeContext();
 const fresh=await second.newPage();
 const failures=[];fresh.on('pageerror',e=>failures.push(e.message));
 fresh.on('dialog',async dialog=>dialog.accept());
 await fresh.goto(url,{waitUntil:'domcontentloaded'});
 await fresh.locator('[data-view="more"]').last().click();
 await fresh.locator('[data-action="import-backup"]').first().click();
 await fresh.locator('#restore-file').setInputFiles(path);
 await fresh.locator('#modal-form button[type=submit]').click();
 await fresh.getByText('Trip ideas').first().waitFor({timeout:15000});
 await fresh.locator('[data-action^="edit-note:"]').first().click();
 assert.equal(await fresh.locator('#f-content').inputValue(),note.data.content);
 assert.equal(failures.length,0,failures.join('; '));
 console.log('N1_BROWSER_PASS: timeline shift, note autosave, reload, checksum backup and fresh-workspace restore');
}finally{if(context)await context.close();if(second)await second.close();await browser.close();server.kill();}
